#!/usr/bin/env python3
"""
Build the score scale for the two-part natural beauty score (quantile mapping to the old V9 distribution).

The blend of the streets and scenery parts runs lower than the old six-component score (mean 47 vs 65).
Instead of a hand-set rescale, each blend value is mapped to the old-score value at the same percentile of
the catalog.  This keeps the score distribution users already know, with no cap and no extra constants.
The table is a calibration to the previous score, not evidence about beauty, and is relative to the catalog
it was built from (21 metros, 1,476 places).  Rebuild only when the catalog changes materially.

Inputs: details.v9_breakdown component scores and details.score_before_two_part (the old score, written by
recompute_natural_beauty_two_part_offline.py).  Outputs: data/natural_beauty_two_part_scale.json and
frontend/lib/nbTwoPartScale.ts (same arrays).

  cd /Users/adamwright/Dev/home-fit
  PYTHONPATH=. python3 scripts/baselines/build_natural_beauty_two_part_scale.py
"""
from __future__ import annotations

import glob
import json
import os
import sys

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)

PCTS = list(range(0, 101))


def _breakdown(nb):
    d = nb.get("details") or {}
    return next((c for c in (d.get("v9_breakdown"), nb.get("v9_breakdown"),
                             (nb.get("breakdown") or {}).get("v9_breakdown"))
                 if isinstance(c, dict) and "gvi_score" in c), None)


def main() -> int:
    from pillars import natural_beauty as NB

    blends, olds = [], []
    for path in sorted(glob.glob(os.path.join(ROOT, "data", "*_metro_place_catalog_scores_merged.composites_recomputed.jsonl"))):
        for line in open(path, encoding="utf-8"):
            nb = ((json.loads(line).get("score") or {}).get("livability_pillars") or {}).get("natural_beauty") or {}
            v9 = _breakdown(nb)
            old = (nb.get("details") or {}).get("score_before_two_part")
            if v9 is None or old is None:
                continue
            i = v9.get("inputs") or {}
            parts = NB.nb_two_part(v9, None, None, scale=False,
                                   streets_missing=NB.streets_inputs_missing(i.get("gvi_pct"), i.get("canopy_pct")))
            if parts:
                blends.append(parts["blend"])
                olds.append(float(old))
    b = np.percentile(blends, PCTS)
    s = np.percentile(olds, PCTS)
    # np.interp needs strictly increasing x: nudge exact ties upward by a hair.
    for i in range(1, len(b)):
        if b[i] <= b[i - 1]:
            b[i] = b[i - 1] + 1e-6
    out = {"n_places": len(blends), "percentiles": PCTS,
           "blend": [round(float(x), 4) for x in b], "score": [round(float(x), 4) for x in s],
           "note": "Quantile map from the two-part blend to the old V9 score distribution. Calibration, not evidence."}
    with open(os.path.join(ROOT, "data", "natural_beauty_two_part_scale.json"), "w") as f:
        json.dump(out, f)
    ts = ("// Generated by scripts/baselines/build_natural_beauty_two_part_scale.py. Do not edit by hand.\n"
          "// Quantile map from the two-part natural beauty blend to the old V9 score distribution.\n"
          f"export const NB_SCALE_BLEND: number[] = {json.dumps(out['blend'])}\n"
          f"export const NB_SCALE_SCORE: number[] = {json.dumps(out['score'])}\n")
    with open(os.path.join(ROOT, "frontend", "lib", "nbTwoPartScale.ts"), "w") as f:
        f.write(ts)
    print(f"{len(blends)} places; blend {b[0]:.1f}..{b[-1]:.1f} -> score {s[0]:.1f}..{s[-1]:.1f}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
